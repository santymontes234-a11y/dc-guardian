"""REGISTRO 1 — permanent engineer record. Never grants access by itself.

Personal data (``engineers``) and biometric data (``face_embeddings``) are kept apart:
- ``face_embeddings`` holds no personal data. Its rows are keyed by an opaque, random
  ``subject_ref`` (UUID4) that only ``engineers.face_embedding_reference`` points to.
- Each embedding is stored encrypted (Fernet, key derived from ``DCG_MASTER_KEY``).
- No face image is ever written to disk: photos/frames are processed in memory and discarded.
"""

from __future__ import annotations

from datetime import datetime

from sqlalchemy import Boolean, Float, ForeignKey, LargeBinary, String
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base
from app.db.types import UTCDateTime, utcnow
from app.models._columns import enum_col
from app.models.enums import EngineerStatus

EMBEDDING_DIM = 512
ENGINEER_ID_PREFIX = "ENG-"


class Engineer(Base):
    __tablename__ = "engineers"

    id: Mapped[int] = mapped_column(primary_key=True)
    # Public identifier ("ENG-0001"), generated by the system, never reused.
    engineer_id: Mapped[str] = mapped_column(String(20), unique=True)
    full_name: Mapped[str] = mapped_column(String(120))
    department: Mapped[str] = mapped_column(String(80))
    position: Mapped[str] = mapped_column(String(80))
    institutional_email: Mapped[str] = mapped_column(String(120), unique=True)
    # Opaque link to the biometric profile; NULL = no face registered.
    face_embedding_reference: Mapped[str | None] = mapped_column(String(36), unique=True)
    registration_date: Mapped[datetime] = mapped_column(UTCDateTime, default=utcnow)
    status: Mapped[EngineerStatus] = mapped_column(
        enum_col(EngineerStatus), default=EngineerStatus.ACTIVE, index=True
    )
    updated_at: Mapped[datetime] = mapped_column(UTCDateTime, default=utcnow, onupdate=utcnow)

    face_embeddings: Mapped[list[FaceEmbedding]] = relationship(
        back_populates="engineer", cascade="all, delete-orphan", order_by="FaceEmbedding.id"
    )
    cards: Mapped[list["RfidCard"]] = relationship(back_populates="engineer")  # noqa: F821

    @property
    def has_face(self) -> bool:
        return bool(self.face_embedding_reference and self.face_embeddings)

    @property
    def face_samples(self) -> int:
        return len(self.face_embeddings) if self.face_embedding_reference else 0


class FaceEmbedding(Base):
    """Biometric sample. Contains no personal data; linked only through ``subject_ref``."""

    __tablename__ = "face_embeddings"

    id: Mapped[int] = mapped_column(primary_key=True)
    subject_ref: Mapped[str] = mapped_column(
        ForeignKey("engineers.face_embedding_reference", ondelete="CASCADE"), index=True
    )
    embedding_encrypted: Mapped[bytes] = mapped_column(LargeBinary)  # Fernet(512 × float32, L2-normalized)
    model_name: Mapped[str] = mapped_column(String(40))
    quality_score: Mapped[float | None] = mapped_column(Float)
    is_primary: Mapped[bool] = mapped_column(Boolean, default=False)
    created_at: Mapped[datetime] = mapped_column(UTCDateTime, default=utcnow)

    engineer: Mapped[Engineer] = relationship(back_populates="face_embeddings")
