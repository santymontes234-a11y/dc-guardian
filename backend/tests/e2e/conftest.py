class Flow:
    """Admin-side steps 1–6 of the main flow, through the public API."""

    def __init__(self, f, door: Door):
        self.f, self.door = f, door
        self._seed = 0

    def engineer(self, *, face: bool = True) -> dict:
        eng = self.f.engineer()  # 1 + 3: registered, ENG-NNNN generated by the system
        assert eng["engineer_id"].startswith("ENG-")
        if face:  # 2: face captured (3 samples)
            self._seed += 1
            eng["_seed"] = 100 + self._seed
            shots = [capture(person(eng["_seed"]), i) for i in range(3)]
            r = self.f.c.post(f"/api/v1/engineers/{eng['id']}/face", files=files(*shots), data={"replace": "true"})
            assert r.status_code == 200, r.text
        return eng

    def card(self, eng: dict | None) -> dict:  # 4: RFID card registered and linked
        return self.f.card(eng["id"] if eng else None)

    def request(self, eng: dict, card: dict, *, start_delta_min: float = -1, minutes: int = 60,
                approve: bool = True) -> dict:  # 5: the engineer asks for authorization
        req = self.f.request(eng, card, self.door.area, start=utcnow() + timedelta(minutes=start_delta_min),
                             minutes=minutes)
        if approve:  # 6: an admin approves it
            req = self.f.ok("POST", f"/api/v1/requests/{req['id']}/approve", json={"notes": "Aprobada en prueba"})
            assert req["status"] == "APROBADA"
        return req

    def authorized(self) -> tuple[dict, dict, dict]:
        eng = self.engineer()
        card = self.card(eng)
        return eng, card, self.request(eng, card)

    def kiosk(self, session_id: str, seed: int, first_shot: int = 50, n: int = 5) -> dict:
        """11–13: the kiosk webcam sends N distinct captures for the waiting session."""
        shots = [capture(person(seed), first_shot + i) for i in range(n)]
        r = self.f.c.post("/api/v1/vision/verify", data={"session_id": session_id},
                          files=[("frames", (f"f{i}.jpg", b, "image/jpeg")) for i, b in enumerate(shots)])
        assert r.status_code == 200, r.text
        return r.json()

    def access(self, uid: str, *, face_seed: int | None, distance: float = 30, close: bool = True):
        """7–17 from the door's point of view."""
        d = self.door.sim  # (the HC-SR04 is inside the room: it plays no part in the access)
        sent = {}

        def between_polls(i):
            if i == 0 and face_seed is not None and d.session_id and not sent:
                sent["kiosk"] = self.kiosk(d.session_id, face_seed)

        res = d.run_access(uid, between_polls=between_polls, max_polls=5, close=close)  # 9–17
        res.kiosk = sent.get("kiosk")
        return res

    def shift_window_to_past(self, request_id: int, minutes: int = 120) -> None:
        """Simulate the passage of time: move a request's window into the past."""
        with SessionLocal() as db:
            now = utcnow()
            db.execute(update(AuthorizationRequest).where(AuthorizationRequest.id == request_id).values(
                start_at=now - timedelta(minutes=minutes), end_at=now - timedelta(minutes=minutes - 30)))
            db.commit()

    def audit_actions(self, **filters) -> list[str]:
        items = self.f.ok("GET", "/api/v1/audit", params={"limit": 200, **filters})["items"]
        return [e["action"] for e in reversed(items)]

    def alerts(self) -> list[dict]:
        return self.f.ok("GET", "/api/v1/alerts", params={"limit": 200})["items"]


