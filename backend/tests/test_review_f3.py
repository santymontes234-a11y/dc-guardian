"""Regression tests for the phase-3 security review findings."""

from datetime import timedelta

import pytest

from app.db.types import utcnow
from app.models import RfidCard
from app.services import requests as svc

REQ = "/api/v1/requests"


def _in_force_now(f):
    eng, card, area = f.setup()
    req = f.request(eng, card, area, start=utcnow() - timedelta(minutes=1))
    f.ok("POST", f"{REQ}/{req['id']}/approve", json={})
    return eng, card, area, req


def _visible(f, db, card, area, req_id):
    listed = [r["id"] for r in f.ok("GET", REQ, params={"in_force": True})["items"]]
    flag = f.ok("GET", f"{REQ}/{req_id}")["in_force"]
    db.rollback()  # drop the read snapshot so we see the API's latest commits
    found = svc.find_in_force(db, card["id"], area["id"], utcnow())
    return req_id in listed, flag, found is not None


# ----------------------------------------------------------------- M1
def test_in_force_baseline(f, db):
    _, card, area, req = _in_force_now(f)
    assert _visible(f, db, card, area, req["id"]) == (True, True, True)


def test_blocked_card_is_not_in_force_anywhere(f, db):
    _, card, area, req = _in_force_now(f)
    f.ok("POST", f"/api/v1/cards/{card['id']}/status", json={"status": "BLOQUEADA", "reason": "Revisión"})
    assert _visible(f, db, card, area, req["id"]) == (False, False, False)
    # the request itself stays APROBADA (blocking is temporary) and comes back when unblocked
    assert f.ok("GET", f"{REQ}/{req['id']}")["status"] == "APROBADA"
    f.ok("POST", f"/api/v1/cards/{card['id']}/status", json={"status": "ACTIVA", "reason": "Revisada"})
    assert _visible(f, db, card, area, req["id"]) == (True, True, True)


def test_locked_card_is_not_in_force(f, db):
    _, card, area, req = _in_force_now(f)
    row = db.get(RfidCard, card["id"])
    row.locked_until = utcnow() + timedelta(minutes=10)  # set by the access engine (F5)
    db.commit()
    assert _visible(f, db, card, area, req["id"]) == (False, False, False)
    f.ok("POST", f"/api/v1/cards/{card['id']}/unlock")
    assert _visible(f, db, card, area, req["id"]) == (True, True, True)


def test_inactive_engineer_is_never_in_force_even_if_request_reopened_by_raw_sql(f, db):
    """Defence in depth: even if a request were left APROBADA, the lookup checks the engineer."""
    from sqlalchemy import text

    eng, card, area, req = _in_force_now(f)
    db.execute(text("UPDATE engineers SET status='SUSPENDIDO' WHERE id=:id"), {"id": eng["id"]})
    db.commit()
    assert _visible(f, db, card, area, req["id"]) == (False, False, False)


def test_card_rebound_to_other_engineer_is_not_in_force(f, db):
    from sqlalchemy import text

    _, card, area, req = _in_force_now(f)
    other = f.engineer()
    db.execute(text("UPDATE rfid_cards SET engineer_id=:e WHERE id=:id"), {"e": other["id"], "id": card["id"]})
    db.commit()
    assert _visible(f, db, card, area, req["id"]) == (False, False, False)


