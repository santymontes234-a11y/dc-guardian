@pytest.mark.parametrize("url,params", [
    ("/api/v1/engineers", {"offset": "99999999999999999999"}),
    ("/api/v1/requests/99999999999999999999", None),
    ("/api/v1/requests", {"engineer_id": "99999999999999999999"}),
    ("/api/v1/cards/0", None),
    ("/api/v1/audit", {"since": "0001-01-01T00:00:00+05:00"}),
    ("/api/v1/audit", {"until": "9999-12-31T23:59:59-05:00"}),
])
def test_out_of_range_inputs_are_422_not_500(api, url, params):
    r = api.get(url, params=params)
    assert r.status_code == 422, r.text
    assert r.json()["error"]["code"] == "VALIDATION_ERROR"


def test_out_of_range_body_ids_and_dates(f):
    eng, card, area = f.setup()
    big = 2**64
    assert f.c.post(REQ, json={"engineer_id": big, "card_id": card["id"], "area_id": area["id"],
                               "reason": "Prueba", "start_at": utcnow().isoformat(),
                               "duration_minutes": 30}).status_code == 422
    assert f.request(eng, card, area, start=utcnow().replace(year=9999), expected=422)
    assert f.c.post(f"/api/v1/cards/{card['id']}/assign", json={"engineer_id": big}).status_code == 422


